-- Mammy családi naptár az OD 4 Supabase-projektben.
-- A mammy_ előtag elkülöníti ezeket a táblákat az OD adataitól.

create table if not exists public.mammy_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 60)
);

create table if not exists public.mammy_entries (
  id bigint generated by default as identity primary key,
  entry_date date not null,
  period text not null check (period in ('am', 'pm')),
  children text[] not null default '{}',
  unavailable boolean not null default false,
  note text not null default '' check (char_length(note) <= 240),
  updated_by uuid not null references public.mammy_profiles(id),
  updated_at timestamptz not null default now(),
  unique (entry_date, period),
  check (not unavailable or cardinality(children) = 0),
  check (children <@ array['ZS', 'MI', 'MA', 'JU']::text[])
);

alter table public.mammy_profiles enable row level security;
alter table public.mammy_entries enable row level security;

create or replace function public.is_mammy_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $function$
  select exists (
    select 1 from public.mammy_profiles where id = auth.uid()
  );
$function$;

revoke all on function public.is_mammy_member() from public;
grant execute on function public.is_mammy_member() to authenticated;

drop policy if exists "Mammy tagok latjak a profilokat" on public.mammy_profiles;
drop policy if exists "Sajat Mammy profil szerkesztheto" on public.mammy_profiles;
drop policy if exists "Mammy tagok latjak a naptarat" on public.mammy_entries;
drop policy if exists "Mammy tagok uj bejegyzest irhatnak" on public.mammy_entries;
drop policy if exists "Mammy tagok bejegyzest szerkeszthetnek" on public.mammy_entries;
drop policy if exists "Mammy tagok bejegyzest torolhetnek" on public.mammy_entries;

create policy "Mammy tagok latjak a profilokat"
on public.mammy_profiles for select to authenticated
using (public.is_mammy_member());

create policy "Sajat Mammy profil szerkesztheto"
on public.mammy_profiles for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "Mammy tagok latjak a naptarat"
on public.mammy_entries for select to authenticated
using (public.is_mammy_member());

create policy "Mammy tagok uj bejegyzest irhatnak"
on public.mammy_entries for insert to authenticated
with check (
  auth.uid() = updated_by
  and public.is_mammy_member()
);

create policy "Mammy tagok bejegyzest szerkeszthetnek"
on public.mammy_entries for update to authenticated
using (public.is_mammy_member())
with check (
  auth.uid() = updated_by
  and public.is_mammy_member()
);

create policy "Mammy tagok bejegyzest torolhetnek"
on public.mammy_entries for delete to authenticated
using (public.is_mammy_member());

alter table public.mammy_entries replica identity full;

do $block$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'mammy_entries'
  ) then
    alter publication supabase_realtime add table public.mammy_entries;
  end if;
end $block$;

